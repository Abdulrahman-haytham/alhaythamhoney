/** نص الإجابة الخام (بلا علامات تنسيق) — للمخطط البنيوي ومحرّكات البحث. */
export function faqPlainAnswer(item: FAQItem): string {
  const text = item.answer.replace(/\*\*(.+?)\*\*/g, '$1').replace(/_(.+?)_/g, '$1');
  const bullets = item.bullets?.map((b) => `• ${b}`).join(' ') ?? '';
  return [text, bullets].filter(Boolean).join(' ').trim();
}
